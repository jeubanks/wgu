#!/usr/bin/env python3
"""Print a MySQL script that runs every statement on the D427 cheat sheet.

CI pipes the output into the MySQL 8.4 job (no --force), so a wrong example on
cheatsheet.md fails the build. The statements come straight from the page:

- each ```sql block runs in order, in one database, on sample tables (BLOCKS);
- each statement in inline code (`ALTER TABLE t ...;`) runs on its own, on a
  fresh small table `t` and parent `p` (SIMPLE, or FULL when it drops a key or
  constraint that has to exist first).

Inline code that isn't a whole statement (no leading keyword or no `;`) is
fragment syntax and isn't run. The script fails if it finds too few statements,
so a reworded page can't make the check pass by running nothing.

    python3 scripts/check_cheatsheet.py | mysql -h 127.0.0.1 -uroot
"""
import re
import sys
from pathlib import Path

PAGE = Path(__file__).resolve().parent.parent / "D427_Data_Management_Applications" / "cheatsheet.md"
FENCE = re.compile(r"^```sql\n(.*?)^```", re.M | re.S)
INLINE = re.compile(r"`([^`\n]+)`")
STATEMENT = re.compile(r"^(ALTER|CREATE|DROP|INSERT|UPDATE|DELETE|TRUNCATE|SELECT)\b.*;$", re.I)
DROPS_KEY = re.compile(r"\bDROP\s+(PRIMARY KEY|FOREIGN KEY|INDEX|CHECK)\b", re.I)
MIN_BLOCKS, MIN_INLINE = 4, 12

BLOCKS = """
CREATE TABLE Horse (ID SMALLINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, Name VARCHAR(20));
CREATE TABLE Student (ID SMALLINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, FirstName VARCHAR(20),
                      LastName VARCHAR(30), City VARCHAR(20), Email VARCHAR(60));
INSERT INTO Student (FirstName, LastName, City) VALUES ('Cara', 'Lin', 'Austin'), ('Dev', 'Patel', 'Waco'),
                                                       ('Eli', 'Moss', 'Austin');
CREATE TABLE Archive (ID SMALLINT UNSIGNED PRIMARY KEY, Name VARCHAR(20));
CREATE TABLE Book (ID INT AUTO_INCREMENT PRIMARY KEY, Title VARCHAR(40), Genre VARCHAR(20),
                   Year SMALLINT, Cost DECIMAL(6,2));
INSERT INTO Book (Title, Genre, Year, Cost) VALUES ('A', 'X', 2001, 10), ('B', 'X', 2005, 20),
                                                   ('C', 'Y', 2010, 5), ('D', 'Y', 1990, 7);
"""
SIMPLE = """
CREATE TABLE p (id INT PRIMARY KEY);
CREATE TABLE t (id INT, other INT, c INT, old VARCHAR(10), x INT);
"""
FULL = """
CREATE TABLE p (id INT PRIMARY KEY);
CREATE TABLE t (id INT PRIMARY KEY, other INT, c INT, old VARCHAR(10), x INT,
                CONSTRAINT fk_name FOREIGN KEY (x) REFERENCES p(id),
                CONSTRAINT uq_name UNIQUE (c),
                CONSTRAINT ck_name CHECK (x > 0));
"""


def fresh(name):
    return f"DROP DATABASE IF EXISTS {name};\nCREATE DATABASE {name};\nUSE {name};\n"


def main():
    text = PAGE.read_text()
    blocks = FENCE.findall(text)
    inline = [s.strip() for s in INLINE.findall(FENCE.sub("", text)) if STATEMENT.match(s.strip())]
    if len(blocks) < MIN_BLOCKS or len(inline) < MIN_INLINE:
        sys.exit(f"check_cheatsheet.py: found {len(blocks)} SQL blocks and {len(inline)} inline statements "
                 f"(expected at least {MIN_BLOCKS} and {MIN_INLINE}); did the page change shape?")
    out = ["-- Generated by scripts/check_cheatsheet.py from cheatsheet.md", fresh("cheatsheet_blocks"), BLOCKS]
    for i, block in enumerate(blocks, 1):
        out.append(f"-- SQL block {i}\n{block}")
    for i, stmt in enumerate(inline, 1):
        fixture = FULL if DROPS_KEY.search(stmt) else SIMPLE
        out.append(f"-- inline statement {i}: {stmt}\n{fresh('cheatsheet_inline')}{fixture}{stmt}\n")
    out.append("DROP DATABASE cheatsheet_blocks;\nDROP DATABASE cheatsheet_inline;\n")
    print("\n".join(out))
    print(f"check_cheatsheet.py: {len(blocks)} SQL blocks, {len(inline)} inline statements", file=sys.stderr)


if __name__ == "__main__":
    main()
